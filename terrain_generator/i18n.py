def normalize_language(language: str | None) -> str:
    """Return a supported language code, defaulting to Chinese."""

    return language if language in SUPPORTED_LANGUAGES else "zh"


def tr(language: str | None, text: str) -> str:
    """Translate a UI string while keeping Chinese as the compatibility default."""

    if normalize_language(language) == "en":
        return ENGLISH_TRANSLATIONS.get(text, text)
    return text
